/**
 * Safely looks up a tooltip definition by case-insensitive key.
 */
export function getTooltip(key: string): string {
  const normalized = key.trim().toLowerCase().replace(/[\s-_]/g, '')
  for (const [k, v] of Object.entries(TOOLTIPS)) {
    if (k.toLowerCase().replace(/[\s-_]/g, '') === normalized) {
      return v
    }
  }
  return TOOLTIPS[key] || 'Telemetry metric / design parameter definition.'
}

